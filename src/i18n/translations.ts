type TranslationBundle = ReturnType<typeof buildTranslations>;
const TRANSLATION_CACHE = new Map<string, TranslationBundle>();

export function getTranslations(region: RegionConfig = REGION): TranslationBundle {
  const cached = TRANSLATION_CACHE.get(region.id);
  if (cached) return cached;
  const built = buildTranslations(region);
  TRANSLATION_CACHE.set(region.id, built);
  return built;
}

